def resolve_country_to_iso2(country_value: str | None) -> str | None:
    """Convert a country name, ISO2, or ISO3 code to a 2-letter ISO code.

    Returns None if the input is empty, unknown, or cannot be resolved.
    """
    if not country_value:
        return None

    stripped = country_value.strip()
    if not stripped or stripped.lower() in ("unknown", ""):
        return None

    upper = stripped.upper()

    # Already a valid ISO2 code
    if len(upper) == 2 and upper in _VALID_ISO2:
        return upper

    # ISO3 code
    if len(upper) == 3 and upper in _ISO3_TO_ISO2:
        return _ISO3_TO_ISO2[upper]

    # Country name lookup (case-insensitive)
    lower = stripped.lower()
    iso2 = _COUNTRY_NAME_TO_ISO2.get(lower)
    if iso2:
        return iso2

    logging.warning(
        "[country_codes] Could not resolve '%s' to ISO2 — add to _COUNTRY_NAME_TO_ISO2 if valid",
        country_value,
    )
    return None
