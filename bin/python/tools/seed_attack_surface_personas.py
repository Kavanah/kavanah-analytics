# the cross-tenant team the connector configure / NLQ surfaces POST
# against. Lives in workspace-b, which NO A-scoped persona can reach, so a
# successful write or a non-404 is a tenant-isolation leak. Must match a team
# created per PERSONAS.md "Manual structure setup".
_CROSS_TENANT_TEAM_TITLE = "Team B1"


def _resolve_team_esid_by_title(es, team_title: str) -> str:
    """Resolve a team TITLE to its esid (de_asset_teams ``_id``), or fail loudly.

    the configure-scope surface needs the raw esid of an
    out-of-workspace team to POST as the cross-tenant target; the gate operates
    on the esid, not the title. Same fail-loud contract as
    ``_resolve_scope_esid``: a missing team means the manual structure setup
    wasn't done, and a silently absent target would make the surface a false
    green.

    Mapping note (verified on staging 2026-06-16): ``de_asset_teams.team_title``
    is mapped as a pure ``keyword`` — NOT the text+keyword multi-field that
    ``de_asset_organization.organization_title`` uses. So we ``term`` the BARE
    field; ``term`` on ``team_title.keyword`` returns 0 (no such subfield). The
    ``.keyword`` trap is per-index — don't assume it applies to every
    ``de_asset_*`` title. A ``term`` on a keyword field is already exact, so a
    >1 hit would mean a genuine duplicate team title; we fail loud on that too
    rather than silently take ``hits[0]``.
    """
    hits = (
        es.search(
            index="de_asset_teams",
            body={"query": {"term": {"team_title": team_title}}, "size": 2},
        )
        .get("hits", {})
        .get("hits", [])
    )
    if not hits:
        raise SeedError(
            f"Cross-tenant target team {team_title!r} not found in de_asset_teams. "
            f"Run `python3 -m tools.seed_attack_surface_structures --apply` first "
            f"(see tests/security/PERSONAS.md 'Manual structure setup')."
        )
    if len(hits) > 1:
        raise SeedError(
            f"Cross-tenant target team {team_title!r} is ambiguous "
            f"({len(hits)}+ matches): {[h['_id'] for h in hits]}. Resolve by hand."
        )
    return hits[0]["_id"]


def _resolve_scope_esid(es, persona: Persona) -> str:
    """Resolve a persona's scope_title to an esid, or fail loudly.

    Failing loudly (rather than skipping) is deliberate: a missing structure
    means the manual setup wasn't done, and a silently scope-less persona is a
    false-green in the suite.
    """
    tier = _TIER[persona.tier]
    query = (
        {"term": {tier["scope_field"]: persona.scope_title}}
        if tier["scope_query"] == "term"
        else {"match": {tier["scope_field"]: persona.scope_title}}
    )
    hit = es.search(index=tier["scope_index"], body={"query": query, "size": 1})
    hits = hit.get("hits", {}).get("hits", [])
    if not hits:
        raise SeedError(
            f"Persona {persona.name!r}: scope {persona.scope_title!r} not found in "
            f"{tier['scope_index']}. Create the structures manually first "
            f"(see tests/security/PERSONAS.md 'Manual structure setup')."
        )
    return hits[0]["_id"]


def _create_account(es, persona: Persona, *, apply: bool, reset_passwords: bool) -> str | None:
    """Create (or skip) the ES Security user; return the known password or None.

    Returns the password the .env should record. None means "leave the existing
    .env line untouched" (account existed and --reset-passwords not passed).
    """
    from asset_management.web.services.user_provisioning_service import UserProvisioningService

    exists = UserProvisioningService._username_exists(es, persona.username)
    # A plain scoped viewer carries NO system role — access comes entirely from
    # the de_authz_user_*_role assignment docs (matches the real create-user
    # flow, app.py:api_create_user). Only the superuser persona gets a system
    # role.
    system_roles = ["superuser"] if persona.is_superuser else []

    if not exists:
        password = _generate_password()
        if not apply:
            _log().info("[DRY] would CREATE %s roles=%s", persona.username, system_roles)
            return password
        result = UserProvisioningService.create_user(
            username=persona.username,
            full_name=f"Attack-surface persona ({persona.name})",
            # Email MUST equal the username. The web login (analytics/routes.py
            # login_post) treats any credential containing '@' as an email and
            # resolves it to a username via find_user_by_email — so an @-form
            # username with an empty email field can never log in through the
            # form (the resolver returns None -> "invalid username or password"
            # BEFORE the password is checked). Setting email=username makes the
            # resolver map it back to itself. (ES-layer auth works either way;
            # only the web form needs this.)
            email=persona.username,
            roles=system_roles,
        )
        if not result.get("success"):
            raise SeedError(f"create_user failed for {persona.username}: {result.get('error')}")
        # Set our known password (create_user set a random one + force_password_change).
        set_res = UserProvisioningService.admin_set_password(
            username=persona.username,
            new_password=password,
            set_by="seed_attack_surface_personas",
            reason="attack-surface regression persona",
        )
        if not set_res.get("success"):
            raise SeedError(f"admin_set_password failed for {persona.username}: {set_res.get('error')}")
        _log().info("CREATED %s (password set, force-change cleared)", persona.username)
        return password

    # Account exists.
    if not reset_passwords:
        _log().info("SKIP %s (exists; pass --reset-passwords to resync its password)", persona.username)
        return None

    password = _generate_password()
    if not apply:
        _log().info("[DRY] would RESET password for existing %s", persona.username)
        return password
    set_res = UserProvisioningService.admin_set_password(
        username=persona.username,
        new_password=password,
        set_by="seed_attack_surface_personas",
        reason="attack-surface regression persona password resync",
    )
    if not set_res.get("success"):
        raise SeedError(f"admin_set_password (reset) failed for {persona.username}: {set_res.get('error')}")
    # Backfill email=username on existing accounts. Accounts created before the
    # email=username fix have email="" and can't log in via the web form (the
    # @-credential email-resolver returns None). --reset-passwords is the resync
    # path, so repair the email here too.
    _ensure_email_matches_username(es, persona)
    _log().info("RESET password + email for %s", persona.username)
    return password


def _ensure_email_matches_username(es, persona: Persona) -> None:
    """Set email=username on an existing ES Security user (preserving roles +
    metadata), so the web login's @-credential email-resolver maps it back."""
    resp = es.security.get_user(username=persona.username)
    user_data = dict(resp).get(persona.username, {})
    if user_data.get("email") == persona.username:
        return  # already correct
    es.security.put_user(
        username=persona.username,
        roles=user_data.get("roles", []),
        full_name=user_data.get("full_name", ""),
        email=persona.username,
        enabled=user_data.get("enabled", True),
        metadata=user_data.get("metadata", {}),
    )
    _log().info("SET email=username for %s", persona.username)


def _stamp_mfa_seed(es, persona: Persona, shared_seed: str, *, apply: bool) -> None:
    """Write a de_asset_user_mfa doc with the shared TOTP seed (encrypted).

    Idempotent upsert keyed on username (matches MFAService.get_mfa_record's
    es.get(index=INDEX, id=username)).
    """
    from lib.encryption import encrypt

    doc = {
        "username": persona.username,
        "mfa_enabled": True,
        "mfa_method": "totp",
        "totp_secret_enc": encrypt(shared_seed),
        "totp_confirmed": True,
        "enabled_by": "seed_attack_surface_personas",
        "enabled_at": datetime.now(timezone.utc).isoformat(),
    }
    if not apply:
        _log().info("[DRY] would STAMP shared MFA seed on %s", persona.username)
        return
    es.index(index="de_asset_user_mfa", id=persona.username, document=doc)
    _log().info("STAMPED MFA seed on %s", persona.username)


def _write_scope_docs(es, persona: Persona, *, apply: bool) -> None:
    """Write the persona's scope as a single role/assignment doc.

     (P3b) retired membership docs: ``_provision_new_authz_assignments``
    in app.py now writes ONLY the role doc (``de_authz_user_*_role``), carrying
    ``is_primary`` — the signal the retired ``de_authz_*_membership`` doc used to
    hold. Readers resolve "belongs to" from the role index ("readers-first").

    So earlier there is no longer a membership-vs-grant-only distinction in
    what gets WRITTEN — every persona is a single role doc. ``persona.grant_only``
    is kept only as a label (it still marks the cohort conceptually
    and drives the .env comment), but it no longer changes the doc shape. We
    mirror app.py exactly: one assignment doc, ``is_primary: False``.
    """
    if persona.tier is None:
        return  # bare / superuser: no scope row
    tier = _TIER[persona.tier]
    scope_esid = _resolve_scope_esid(es, persona)
    role_esid = persona.role_esid or tier["default_role"]
    now = datetime.now(timezone.utc).isoformat()

    # Matches app.py:_provision_new_authz_assignments earlier.
    assignment_doc = {
        "username": persona.username,
        tier["scope_esid_field"]: scope_esid,
        "role_esid": role_esid,
        "is_primary": False,
        "created_at": now,
    }
    assignment_id = f"{persona.username}:{scope_esid}:{role_esid}"

    label = "" if persona.grant_only else ""
    if apply:
        es.index(index=tier["assignment_index"], id=assignment_id, document=assignment_doc)
        _log().info("WROTE role doc %s -> %s%s", persona.username, assignment_id, label)
    else:
        _log().info("[DRY] would WRITE role doc %s -> %s%s", persona.username, assignment_id, label)


def _render_env(
    base_url: str,
    shared_seed: str,
    passwords: dict[str, str | None],
    existing: dict[str, str],
    forbidden_team_esid: str,
) -> str:
    """Build the .env.attack-surface body.

    passwords: persona.name -> new password, or None to reuse `existing`.
    existing:  parsed key=value from the current .env (so skipped accounts keep
               their password line).
    forbidden_team_esid: the resolved esid of the cross-tenant target
               team (Team B1 in workspace-b); written as TEST_FORBIDDEN_TEAM_ESID
               for the configure-scope + NLQ-scope surfaces.
    """

    # Every VALUE is single-quoted. The runner sources this file under
    # `set -euo pipefail`; an unquoted value containing a space or comma
    # (e.g. FORBIDDEN_ORGS=Control Org,Org B) parses as a command, and one
    # containing $ aborts on `set -u`. Single-quoting makes `source` treat
    # every value literally. A literal single quote can't appear in any value
    # we emit (titles + generated passwords), so escaping isn't needed.
    def kv(key: str, value: str) -> str:
        return f"{key}='{value}'\n"

    lines: list[str] = [_ENV_HEADER, kv("TEST_BASE_URL", base_url), "\n"]
    # Chart-stat keys — keep whatever's already there, else sensible defaults.
    chart_defaults = {
        "TEST_CHART_STAT_FACEBOOK": "reach",
        "TEST_CHART_STAT_ECHO": "messages",
        "TEST_CHART_STAT_GOOGLE_ADS": "google_ads_app_installs",
        "TEST_CHART_STAT_DT": "baptisms",
    }
    for k, default in chart_defaults.items():
        lines.append(kv(k, existing.get(k, default)))
    lines.append("\n")

    # cross-tenant target team esid (Team B1, workspace-b) for the
    # connector configure-scope + NLQ-scope surfaces. Shared (not per-persona):
    # it's the same out-of-workspace team for every A-scoped persona.
    lines.append("# out-of-workspace team the configure/NLQ surfaces target.\n")
    lines.append(kv("TEST_FORBIDDEN_TEAM_ESID", forbidden_team_esid))
    lines.append("\n")

    for p in PERSONAS:
        lines.append(f"# {p.name}{'' if p.grant_only else ''}\n")
        lines.append(kv(f"{p.env_prefix}_USERNAME", p.username))
        pw_key = f"{p.env_prefix}_PASSWORD"
        new_pw = passwords.get(p.name)
        pw_val = new_pw if new_pw is not None else existing.get(pw_key, "")
        lines.append(kv(pw_key, pw_val))
        if p.is_superuser:
            lines.append(kv(f"{p.env_prefix}_IS_SUPERUSER", "true"))
        if p.expects_empty_scope:
            lines.append(kv(f"{p.env_prefix}_EXPECTS_EMPTY_SCOPE", "true"))
        if p.can_see_user_management:
            lines.append(kv(f"{p.env_prefix}_CAN_SEE_USER_MANAGEMENT", "true"))
        for suffix, val in {**p.allowed, **p.forbidden}.items():
            lines.append(kv(f"{p.env_prefix}_{suffix}", val))
        lines.append("\n")

    lines.append("# Shared second-factor seed — stamped on all personas.\n")
    lines.append(kv("PERSONA_SHARED_MFA_SECRET", shared_seed))
    return "".join(lines)


def _parse_existing_env(path: str) -> dict[str, str]:
    out: dict[str, str] = {}
    if not os.path.isfile(path):
        return out
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, _, v = line.partition("=")
            v = v.strip()
            # Strip one layer of surrounding quotes (passwords are written
            # single-quoted) so reused values don't accumulate quotes on
            # repeated runs.
            if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"'):
                v = v[1:-1]
            out[k.strip()] = v
    return out


def _write_env_file(path: str, body: str, *, apply: bool) -> None:
    if not apply:
        _log().info("[DRY] would WRITE %s (mode 600, %d bytes)", path, len(body))
        return
    # Credentials must never be world-readable, not even between create and
    # chmod: create with 0600, and tighten a pre-existing file
    # before a single byte is written to it.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    _log().info("WROTE %s (mode 600)", path)


def _resolve_shared_seed(existing: dict[str, str], apply: bool) -> str:
    """Reuse an existing PERSONA_SHARED_MFA_SECRET, else generate one."""
    seed = existing.get("PERSONA_SHARED_MFA_SECRET", "").strip()
    if seed:
        _log().info("Reusing existing PERSONA_SHARED_MFA_SECRET from .env.")
        return seed
    import pyotp

    seed = pyotp.random_base32()
    _log().info("Generated a fresh PERSONA_SHARED_MFA_SECRET.")
    return seed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Seed attack-surface persona accounts.")
    parser.add_argument("--base-url", required=True, help="TEST_BASE_URL written into .env (and prod guard).")
    parser.add_argument(
        "--env-file",
        default=None,
        help="Path to .env.attack-surface to read/write. Default: <repo>/.env.attack-surface or $ATTACK_SURFACE_ENV.",
    )
    parser.add_argument("--apply", action="store_true", help="Actually write. Default is a dry run.")
    parser.add_argument(
        "--reset-passwords",
        action="store_true",
        help="Reset the password of accounts that already exist and rewrite their .env line (resync).",
    )
    parser.add_argument(
        "--prod",
        action="store_true",
        help=f"Permit a prod hostname (requires {_ALLOW_PROD_ENV}=1 too).",
    )
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    log = _log()

    try:
        _refuse_prod(args.base_url, args.prod)
    except SeedError as e:
        log.error("%s", e)
        return 2

    # Resolve the env-file path.
    env_path = args.env_file or os.environ.get("ATTACK_SURFACE_ENV")
    if not env_path:
        for candidate in (
            os.path.expanduser("~/kavanah-analytics/.env.attack-surface"),
            os.path.expanduser("~/DE-Reporting/.env.attack-surface"),
            os.path.expanduser("~/.env.attack-surface"),
        ):
            if os.path.isdir(os.path.dirname(candidate)):
                env_path = candidate
                break
    if not env_path:
        log.error("Could not determine an env-file path. Pass --env-file or set ATTACK_SURFACE_ENV.")
        return 2

    if not args.apply:
        log.info("=== DRY RUN (no writes). Re-run with --apply to commit. ===")

    try:
        es = _get_es()
        existing = _parse_existing_env(env_path)
        shared_seed = _resolve_shared_seed(existing, args.apply)

        passwords: dict[str, str | None] = {}
        for persona in PERSONAS:
            log.info("--- persona: %s (%s) ---", persona.name, "grant-only" if persona.grant_only else "membership")
            passwords[persona.name] = _create_account(es, persona, apply=args.apply, reset_passwords=args.reset_passwords)
            _stamp_mfa_seed(es, persona, shared_seed, apply=args.apply)
            _write_scope_docs(es, persona, apply=args.apply)

        # the connector configure / NLQ surfaces target a team that
        # lives OUTSIDE the A-scoped personas' workspace (Team B1 in
        # workspace-b). The gate keys off the team ESID, not a title, so resolve
        # it once here and emit it as TEST_FORBIDDEN_TEAM_ESID. Fails loudly via
        # _resolve_team_esid_by_title if the structure is missing — a missing
        # target would otherwise make the configure-scope surface a false green.
        forbidden_team_esid = _resolve_team_esid_by_title(es, _CROSS_TENANT_TEAM_TITLE)

        body = _render_env(args.base_url, shared_seed, passwords, existing, forbidden_team_esid)
        _write_env_file(env_path, body, apply=args.apply)
    except SeedError as e:
        log.error("ABORTED: %s", e)
        return 1

    log.info("Done.%s", "" if args.apply else "  (dry run — nothing written)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
