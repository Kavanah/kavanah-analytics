#!/usr/bin/env python3
"""seed_attack_surface_personas.py — provision the attack-surface persona accounts.

. This is the "Phase 2 wrapper" that
``deployment/generate-attack-surface-env.sh`` deferred: it creates the persona
ES Security accounts, sets known passwords, stamps a shared MFA seed, writes the
scope docs (membership-bearing OR grant-only depending on persona shape), and
emits/updates ``.env.attack-surface`` so the credential file always matches the
accounts that actually exist.

WHAT IT DOES
    For each of the 10 personas:
      1. Create the ES Security user (skip if it already exists — guard
         in UserProvisioningService.create_user handles the collision).
      2. Set a KNOWN password via admin_set_password (clears force_password_change
         so the suite's scripted /login works headless). On first create we set
         the password we just generated; on re-runs we skip unless
         --reset-passwords is passed.
      3. Stamp the shared TOTP seed on the user's de_asset_user_mfa doc so the
         suite exercises the real /mfa/challenge flow.
      4. Write the scope doc: a single de_authz_user_*_role role doc per tier
         (mirrors _provision_new_authz_assignments in app.py). (P3b)
         retired the de_authz_*_membership docs — the role doc now carries the
         is_primary signal and readers resolve "belongs to" from the role index.
         So every persona is a single role doc; the ``grant_only`` flag on the
          cohort (team_grant, org_grant, workspace_member,
         workspace_grant) is now only a label, not a different doc shape.
      5. Emit/update .env.attack-surface (mode 600) with usernames, passwords,
         the shared MFA seed, and the FORBIDDEN_*/ALLOWED_* values.

WHAT IT DOES NOT DO
    Create the organizational structures (workspaces / orgs / teams) or the two
    tripwire assets. Those are a
    one-time manual setup via the Asset Explorer UI — see tests/security/
    PERSONAS.md "Manual structure setup". This tool RESOLVES those structures by
    title/slug and fails loudly if one is missing, so you run the manual
    checklist first, then this.

SAFETY
    - Dry-run by default. Pass --apply to write.
    - Refuses prod unless BOTH --prod and ATTACK_SURFACE_ALLOW_PROD=1 are set
      (same opt-in token as deployment/run-attack-surface-tests.sh and the
      suite's conftest). The personas are throwaway test accounts; creating them
      on prod is a deliberate, gated act.
    - Runs in-container against ES via lib.es_helpers.get_elasticsearch_client.
      No admin login, no superuser credential anywhere.

USAGE (inside imports_container)
    # staging dry-run (default)
    python3 -m tools.seed_attack_surface_personas --base-url https://<staging-host>
    # staging apply
    python3 -m tools.seed_attack_surface_personas --base-url https://<staging-host> --apply
    # resync passwords into a lost/stale .env
    python3 -m tools.seed_attack_surface_personas --base-url ... --apply --reset-passwords
    # prod apply (deliberate, gated)
    ATTACK_SURFACE_ALLOW_PROD=1 python3 -m tools.seed_attack_surface_personas \
        --base-url https://kavanahanalytics.com --prod --apply
"""

