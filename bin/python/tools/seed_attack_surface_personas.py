class SeedError(Exception):
    """Base for seeder failures."""


def _log() -> logging.Logger:
    return logging.getLogger("seed_attack_surface")


def _generate_password() -> str:
    """16-char password meeting validate_admin_password_complexity."""
    upper = secrets.choice(string.ascii_uppercase)
    lower = secrets.choice(string.ascii_lowercase)
    digit = secrets.choice(string.digits)
    special = secrets.choice(_PASSWORD_SPECIALS)
    rest = [secrets.choice(string.ascii_letters + string.digits) for _ in range(12)]
    parts = [upper, lower, digit, special] + rest
    secrets.SystemRandom().shuffle(parts)
    return "".join(parts)


def _refuse_prod(base_url: str, prod_flag: bool) -> None:
    """Hard-fail on a prod hostname unless the explicit opt-in is present.

    The opt-in is BOTH the --prod flag AND the ATTACK_SURFACE_ALLOW_PROD=1 env
    var — belt and suspenders so neither alone trips it.
    """
    lower = base_url.lower()
    is_prod = is_prod_host(lower)
    if not is_prod:
        return
    allowed_env = os.environ.get(_ALLOW_PROD_ENV) == "1"
    if prod_flag and allowed_env:
        _log().warning("PROD opt-in present (--prod + %s=1). Proceeding against %s.", _ALLOW_PROD_ENV, base_url)
        return
    raise SeedError(
        f"Refusing to seed personas against production ({base_url}). "
        f"To do this deliberately, pass --prod AND set {_ALLOW_PROD_ENV}=1."
    )


