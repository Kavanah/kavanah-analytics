"""Validation for pasted Meta system-user tokens.

The wizard's OAuth path is unchanged and remains the self-serve default. This is
the advanced alternative: a Business Manager **system user** token, which has no
expiry and no data-access clock, so a connection using one never joins the
90-day re-auth treadmill.

Why paste rather than OAuth: Meta has no API to mint a system-user token on
someone's behalf. They are generated by hand in business.facebook.com, so the
only thing the app can do is accept one and check it hard before trusting it.

What "check it hard" means here
-------------------------------
Three failures are possible at paste time, and all three are silent if unchecked:

1. **Wrong token type.** A user token pasted here would be accepted, work
   perfectly for 90 days, then die — and the operator would believe they were on
   the non-expiring path. Rejected outright; that is the whole point of the
   feature.
2. **Missing scopes.** Measured on prod 2026-08-27: three of six real system
   users lack ``read_insights``, and without it Meta returns 200 with an empty
   ``data[]`` for page insights — no error, nothing to alarm on. Those clients
   had silently empty page insights. A scope check at paste time is
   the cheapest possible place to catch that.
3. **Assets not shared with the system user.** Handled by the caller via
    coverage machinery, not here.

Never logs or echoes the token (CLAUDE.md #26/#43). Every return value is
structural: type, scope names, counts.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any

TOKEN_KIND_SYSTEM_USER = "system_user"
TOKEN_KIND_USER = "user"

# Meta's own name for a system-user principal in /debug_token's `type`.
_META_TYPE_SYSTEM_USER = "SYSTEM_USER"

# Which capability each scope buys. Used to explain a missing scope in terms of
# what the operator LOSES, not as a bare permission string — "missing
# read_insights" means nothing to a client admin; "page insights will import as
# empty" is actionable. Same reasoning as.
SCOPE_CAPABILITIES: dict[str, str] = {
    "read_insights": "Facebook page insights",
    "pages_show_list": "listing the Pages this connection can reach",
    "pages_read_engagement": "Facebook page engagement metrics",
    "ads_read": "ad account insights",
    "business_management": "enumerating assets in the Business Manager",
    "instagram_basic": "Instagram profile data",
    "instagram_manage_insights": "Instagram insights",
}


@dataclass
class TokenValidation:
    """Outcome of validating a pasted token. Carries no token material."""

    ok: bool = False
    # Machine-readable failure reason: "unreachable" | "invalid" | "wrong_type"
    # | "missing_scopes" | "" when ok.
    code: str = ""
    message: str = ""
    token_type: str = ""
    system_user_id: str = ""
    app_id: str = ""
    granted_scopes: list[str] = field(default_factory=list)
    missing_scopes: list[str] = field(default_factory=list)
    lost_capabilities: list[str] = field(default_factory=list)

    def as_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "code": self.code,
            "message": self.message,
            "token_type": self.token_type,
            "system_user_id": self.system_user_id,
            "app_id": self.app_id,
            "granted_scopes": list(self.granted_scopes),
            "missing_scopes": list(self.missing_scopes),
            "lost_capabilities": list(self.lost_capabilities),
        }


def required_scopes() -> tuple[str, ...]:
    """The scope set a Meta connection needs, from the wizard's own source.

    Deliberately reads ``WizardOAuthService.default_scopes_for("meta_ads")``
    rather than restating the list: the two paths must ask for the same
    permissions or a system-user connection would quietly import less than a
    wizard one, which is exactly the class of divergence this feature exists to
    avoid. Falls back to an empty tuple so a config problem degrades to "cannot
    check scopes" rather than "reject every token".
    """
    try:
        from asset_management.web.services.wizard_oauth_service import WizardOAuthService

        return tuple(WizardOAuthService.default_scopes_for("meta_ads") or ())
    except Exception as exc:  # noqa: BLE001
        logging.warning("could not resolve required scopes: %s", exc)
        return ()


def validate_system_user_token(token: str, app_id: str, app_secret: str) -> TokenValidation:
    """Check a pasted token before anything is persisted.

    Read-only against Meta (`/debug_token`). Returns a TokenValidation; never
    raises, never includes the token in its output.
    """
    out = TokenValidation()
    if not (token or "").strip():
        out.code = "invalid"
        out.message = "No token was provided."
        return out

    try:
        from lib.credential_prober import probe_token

        probe = probe_token(token.strip(), app_id, app_secret)
    except Exception as exc:  # noqa: BLE001
        logging.warning("probe_token raised: %s", type(exc).__name__)
        out.code = "unreachable"
        out.message = "Could not reach Meta to check this token. Try again shortly."
        return out

    if not probe.reachable:
        out.code = "unreachable"
        out.message = "Could not reach Meta to check this token. Try again shortly."
        return out

    out.token_type = probe.token_type
    out.app_id = probe.app_id
    out.granted_scopes = list(probe.scopes)

    if not probe.is_valid:
        out.code = "invalid"
        out.message = probe.error or "Meta rejected this token."
        return out

    # Hard reject a user token. Accepting one would silently defeat the entire
    # feature: it works for 90 days, then dies, while the operator believes they
    # are on the non-expiring path.
    if probe.token_type != _META_TYPE_SYSTEM_USER:
        out.code = "wrong_type"
        out.message = (
            f"This is a {probe.token_type or 'user'} token, not a system user token. "
            "Only system user tokens avoid Meta's 90-day expiry — generate one under "
            "Business Settings → Users → System Users, or go back and use "
            "Continue with Facebook."
        )
        return out

    out.system_user_id = probe.user_id

    needed = required_scopes()
    if needed:
        granted = set(probe.scopes)
        missing = [s for s in needed if s not in granted]
        if missing:
            out.missing_scopes = missing
            out.lost_capabilities = [SCOPE_CAPABILITIES.get(s, s) for s in missing]
            out.code = "missing_scopes"
            out.message = (
                "This token is missing "
                + ", ".join(missing)
                + ". Without "
                + ("them" if len(missing) > 1 else "it")
                + ", "
                + _humanise(out.lost_capabilities)
                + " will not import — and Meta reports no error when that happens, "
                "so the data would simply be empty. Add the permission"
                + ("s" if len(missing) > 1 else "")
                + " to the system user in Business Manager and generate a new token."
            )
            return out
    else:
        logging.warning(
            "required-scope list unavailable; accepting token without a "
            "scope check (structure and type were verified)"
        )

    out.ok = True
    out.message = "System user token accepted — this connection will not expire."
    return out


def team_assets_for_coverage(team_esid: str) -> list[dict[str, Any]]:
    """The Meta assets a new token must reach for this team, in prober shape.

     coverage check reads ``de_connection_asset`` — correct there,
    because it is re-authorising an EXISTING connection that already has asset
    rows. A system-user connection is being established for the first time, so
    those rows do not exist yet and the team's own configuration is the only
    statement of what it needs.

    Sourced from the three fields that actually carry it (measured across the 38
    ds_facebook teams on prod, 2026-08-28):

        team_facebook_page_id              37/38
        fb_ad_account_links[].fb_ad_account_id  36/38
        ig_account_id                      15/38

    ``team_facebook_page_esids`` is deliberately NOT used — it is the internal
    asset-doc id, and the prober needs Meta's own numeric id.

    Returns [] when the team has nothing configured or cannot be read; the
    caller treats an empty list as "no coverage requirement", which commits.
    """
    if not team_esid:
        return []
    try:
        from lib.es_helpers import get_document_by_id

        team = get_document_by_id("de_asset_teams", team_esid) or {}
    except Exception as exc:  # noqa: BLE001
        logging.warning("could not read team %s: %s", team_esid, type(exc).__name__)
        return []

    def _as_list(v):
        if v is None:
            return []
        return v if isinstance(v, list) else [v]

    assets: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()

    def _add(asset_type: str, asset_id, name: str = "", parent: str = ""):
        aid = str(asset_id or "").strip()
        if not aid or (asset_type, aid) in seen:
            return
        seen.add((asset_type, aid))
        row: dict[str, Any] = {"asset_type": asset_type, "asset_id": aid, "asset_name": name}
        if parent:
            row["parent_page_id"] = parent
        assets.append(row)

    # the prober fetches names from Meta on a SUCCESSFUL probe — but
    # a FAILED row (the one the operator must judge) rendered as a bare numeric
    # id. Seed names from our own asset docs so every row is identifiable
    # regardless of probe outcome. Fail-soft: a lookup failure keeps "".
    names = {
        "page": _asset_names("de_asset_fb_pages", "fb_page_id", ["fb_page_name"]),
        "ad_account": _asset_names("de_asset_fb_ad_accounts", "fb_ad_account_id", ["fb_ad_account_title"]),
        # An IG account is best known by its @handle; title is the fallback.
        "ig": _asset_names("de_asset_ig_accounts", "ig_account_id", ["ig_account_username", "ig_account_title"]),
    }

    pages = [str(p) for p in _as_list(team.get("team_facebook_page_id")) if p]
    for pid in pages:
        _add("page", pid, name=names["page"].get(pid, ""))

    for link in _as_list(team.get("fb_ad_account_links")):
        if isinstance(link, dict):
            aid = str(link.get("fb_ad_account_id") or "").strip()
            _add("ad_account", aid, name=names["ad_account"].get(aid, ""))

    # An IG account is reached THROUGH its Page, and the prober uses
    # ``parent_page_id`` to report a downstream IG failure as "caused by" that
    # page instead of as a second independent fault.
    #
    # But the team config does NOT record which Page each IG account hangs off —
    # only two flat lists. So the parent is only claimed when the pairing is
    # UNAMBIGUOUS: exactly one page and exactly one IG account. Measured on prod
    # 2026-08-28, teams routinely break that assumption (team A has 1 page and 2
    # IG accounts; team B has 5 and 5), and an IG business account belongs to
    # exactly one Page — so attributing several IGs to a single page would
    # produce a confidently wrong causation message. No attribution is better
    # than a wrong one; the assets then simply report independently.
    #
    # Resolving the real mapping needs Meta's instagram_business_account edge —
    # worth doing if the pairing turns out to matter, but not guessed at here.
    igs = [str(i) for i in _as_list(team.get("ig_account_id")) if i]
    parent = pages[0] if (len(pages) == 1 and len(igs) == 1) else ""
    for ig in igs:
        _add("ig", ig, name=names["ig"].get(ig, ""), parent=parent)

    return assets


def _asset_names(index: str, id_field: str, name_fields: list[str]) -> dict[str, str]:
    """provider-id -> display-name map from one legacy asset index.

    ``name_fields`` is a preference list; the first non-empty value wins.
    Returns {} on any failure — coverage rows then fall back to the raw id,
    which is exactly the earlier behavior.
    """
    try:
        from lib.es_helpers import get_elasticsearch_client

        es = get_elasticsearch_client()
        if es is None:
            return {}
        hits = es.search(
            index=index,
            body={"query": {"match_all": {}}, "size": 2000, "_source": [id_field, *name_fields]},
        )[
            "hits"
        ]["hits"]
    except Exception as exc:  # noqa: BLE001 — display-only enrichment, never block coverage
        logging.warning("name lookup on %s failed: %s", index, type(exc).__name__)
        return {}

    out: dict[str, str] = {}
    for hit in hits:
        src = hit.get("_source") or {}
        aid = str(src.get(id_field) or "").strip()
        if not aid:
            continue
        for nf in name_fields:
            if src.get(nf):
                out[aid] = str(src[nf])
                break
    return out


def _humanise(items: list[str]) -> str:
    """'a', 'a and b', 'a, b and c' — for user-facing copy."""
    if not items:
        return ""
    if len(items) == 1:
        return items[0]
    return ", ".join(items[:-1]) + " and " + items[-1]
